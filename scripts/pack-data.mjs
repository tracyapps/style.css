import { readFile, writeFile } from "node:fs/promises";
import { gzipSync } from "node:zlib";
const source = new URL("../src/data/catalog.json", import.meta.url);
const data = await readFile(source);
await writeFile(
  new URL("../src/data/catalog.json.gz", import.meta.url),
  gzipSync(data, { level: 9 }),
);
console.log(
  `Packed reference: ${data.length.toLocaleString()} bytes → ${gzipSync(data, { level: 9 }).length.toLocaleString()} bytes`,
);

// Paint-chip data: the compiled preview runtime carries every default theme
// color variable. Split them into named palettes for the chip walls.
const runtime = await readFile(
  new URL("../src/data/preview-runtime.css", import.meta.url),
  "utf8",
);
const palettes = {};
const solos = {};
for (const [, name, value] of runtime.matchAll(
  /--color-([a-z0-9]+(?:-[a-z0-9]+)*):([^;]+);/g,
)) {
  const shade = name.match(/-\d+$/)?.[0];
  if (shade) {
    const palette = name.slice(0, -shade.length);
    (palettes[palette] ??= {})[shade.slice(1)] = value.trim();
  } else {
    solos[name] = value.trim();
  }
}
const paletteCount = Object.keys(palettes).length;
if (paletteCount < 20)
  throw new Error("Palette extraction found too few palettes; runtime changed?");
const module = `// Generated by scripts/pack-data.mjs — do not edit by hand.
// Source: Tailwind theme color variables compiled into preview-runtime.css.
export interface PaintData {
  palettes: Record<string, Record<string, string>>;
  solos: Record<string, string>;
}
export const palettes: Record<string, Record<string, string>> = ${JSON.stringify(palettes)};
export const solos: Record<string, string> = ${JSON.stringify(solos)};
`;
await writeFile(new URL("../src/data/palettes.ts", import.meta.url), module);
console.log(
  `Paint chips: ${paletteCount} palettes · ${Object.keys(solos).length} solo colors`,
);
